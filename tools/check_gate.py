#!/usr/bin/env python3
"""T6 compile gate — the assertions that follow `moon check` / `moon info`.

Run from the module root, ALWAYS after `moon info` (D-8: a `.mbti` assertion
taken before the refresh can be false-green — see the T6 report, Step A).

    python tools/check_gate.py [--json PATH] [--mbti-log PATH] [--dialect-log PATH]

What it asserts
---------------
N8  (15 packages)   `_build/native/debug/check/all_pkgs.json` holds exactly 15
                    module-local packages and their rel-set equals the frozen
                    list (the 14 sub-packages plus the empty-rel root package
                    that carries lang_registry.mbt).
AD2-1..AD2-5        `runtime/pkg.generated.mbti` counts (28 / 5 / 6 / 1 / 1 / 1).
AD2-2, AD2-8        each of the 12 language packages exposes exactly 3 `^pub`
                    entries and exactly 1 `stem_word(...raise @runtime.Lab`.
D-1                  `tools/d1check.py` per package (13 dirs; the root package is
                    checked through a temp copy of its own *.mbt so that the
                    scanner never sees `.probe/`), plus the two fail-closed cases
                    (missing root -> 2, empty dir -> 3).
D-2..D-6, D-14      the retrieval greps, scoped to the 15 module-local packages
                    that all_pkgs.json just proved exist.  Scope rationale:
                    `.probe/`, `.planning/tmp/`, `_build/` and `.mooncakes/` are
                    forensic/build residue, not deliverables; scanning them is the
                    same defect B7 rejected for D-1.  The literal `.`-scoped
                    counts are still reported, attributed, so the difference is
                    visible rather than hidden.
D-12 (amended)      `cmd/golden/main.mbt` has an explicit non-zero exit path:
                    either `fn main` itself carries `raise`, or `main` is a
                    non-raising wrapper that calls a raising function and ends
                    in `native_exit`/`abort`/`raise` (the shipped shape:
                    `let code = run() catch { _ => 1 }; native_exit(code)`).
                    Controller ruling 2026-10-23; see the D-12 revision
                    blockquote in the plan.

Exit codes: 0 pass, 1 an assertion failed, 2 usage / missing input.
Nothing here writes into a source package: the only writes are the two logs
named on the command line.
"""

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

# The eleven delivered languages plus the porter311 control package: 12
# `.mbti` faces, 12 stanza-2 rows.  porter311 is never registered in
# lang_registry.mbt and never generated by the upstream compiler.
LANG_PKGS = [
    "arabic", "dutch", "english", "french", "german", "italian",
    "porter", "porter311", "portuguese", "russian", "spanish", "turkish",
]

# The 15 module-local packages, as `rel` values: 14 sub-packages (12 languages
# + runtime + cmd/golden) plus the empty-rel root package.
EXPECTED_RELS = {""} | set(LANG_PKGS) | {"runtime", "cmd/golden"}

# D-1 runs per package: runtime carries the two `nobreak` sites; every language
# package is scanned so that a generated `while true` can never slip through.
D1_PKGS = ["runtime"] + LANG_PKGS

# AD2-1..AD2-5, measured on runtime/pkg.generated.mbti after `moon info`.
RUNTIME_COUNTS = [
    ("AD2-1", r"^pub fn", 28),
    ("AD2-3", r"^  Lab[0-4]$", 5),
    ("AD2-4", r"^  mut ", 6),
    ("AD2-5a", r"^pub\(all\) struct Env", 1),
    ("AD2-5b", r"^pub\(all\) suberror Lab", 1),
    ("AD2-5c", r"^pub\(all\) struct Among", 1),
]

STEM_RE = re.compile(r"pub fn stem_word\(.*raise @runtime\.Lab")

# D-2..D-6 / D-14 retrieval patterns.  `glob` narrows the file population the
# same way the contract's command does (`*/*_gen.mbt` for D-3 and D-6).
RED_LINES = [
    ("D-2", "to_int16", "*.mbt", None),
    ("D-3", r'current\[[^]]*\] *[!=]= *"', "*_gen.mbt", None),
    ("D-4", r"^fn [A-Za-z_]+\(self *:", "*.mbt", None),
    ("D-5", r"substring\(", "*.mbt", None),
    ("D-6", r"@rt::", "*_gen.mbt", None),
    # AD1-3/4/5 residue (generated-code contract §5).
    ("AD1-3", r"self\.", "*_gen.mbt", None),
    ("AD1-4", r"@rt::", "*_gen.mbt", None),
    ("AD1-5", r" in range\(", "*_gen.mbt", None),
]

# Directories that are never part of the delivery tree.  `.probe/` is the
# forensic archive, `.planning/tmp/` holds U1 copies, `_build/`/`.mooncakes/`
# are build residue: all four are gitignored or excluded by the contract.
NON_DELIVERY_DIRS = {
    ".probe", ".planning", "_build", ".mooncakes", "build", "stray",
    "docs", "snowball", ".git", "tools", "scripts",
}

FAILS = []
NOTES = []


def note(line):
    NOTES.append(line)
    print(line)


def fail(line):
    FAILS.append(line)
    print(line)


# ---------------------------------------------------------------------------
# N8 — the 15 package assertion
# ---------------------------------------------------------------------------

def module_name(root):
    """The module name, read from moon.mod (`name = "<owner>/<name>"`)."""
    text = (root / "moon.mod").read_text(encoding="utf-8", errors="replace")
    m = re.search(r'^\s*name\s*=\s*"([^"]+)"', text, re.M)
    if not m:
        fail("N8 FAIL: no `name = \"...\"` line in moon.mod")
        return None
    return m.group(1)


def check_packages(root):
    """Parse all_pkgs.json; return (count, rel-set) of module-local packages."""
    pkg_json = root / "_build/native/debug/check/all_pkgs.json"
    if not pkg_json.is_file():
        fail("N8 FAIL: %s is missing (moon check did not run?)" % pkg_json)
        return None, set()
    data = json.loads(pkg_json.read_text(encoding="utf-8"))
    mod = module_name(root)
    rels = sorted({p.get("rel", "") for p in data.get("packages", [])
                   if p.get("root") == mod})
    n = len(rels)
    if n != 15:
        fail("N8 FAIL: module-local package count = %d, expected 15 (%s)" % (n, rels))
    else:
        note("N8: packages=%d (14 sub-packages + empty-rel root)" % n)
    missing = sorted(EXPECTED_RELS - set(rels))
    extra = sorted(set(rels) - EXPECTED_RELS)
    if missing or extra:
        fail("N8 FAIL: rel-set diff: missing=%s extra=%s" % (missing, extra))
    else:
        note("N8: rel-set == expected 15 (%s)" % ", ".join(
            "<root>" if r == "" else r for r in rels))
    return n, set(rels)


# ---------------------------------------------------------------------------
# AD2 — `.mbti` counts (only meaningful after `moon info`)
# ---------------------------------------------------------------------------

def count_lines(path, pattern):
    rx = re.compile(pattern)
    return sum(1 for line in path.read_text(encoding="utf-8").splitlines()
               if rx.search(line))


def stem_count(path):
    rx = STEM_RE
    return sum(1 for line in path.read_text(encoding="utf-8").splitlines()
               if rx.search(line))


def check_mbti(root, mbti_log):
    lines = []
    runtime_mbti = root / "runtime/pkg.generated.mbti"
    if not runtime_mbti.is_file():
        fail("AD2 FAIL: %s is missing (run moon info first)" % runtime_mbti)
        return
    for tag, pattern, want in RUNTIME_COUNTS:
        got = count_lines(runtime_mbti, pattern)
        lines.append("runtime/pkg.generated.mbti  %-8s %-28s got=%-3d want=%d %s"
                     % (tag, pattern, got, want, "OK" if got == want else "FAIL"))
        if got != want:
            fail("AD2 FAIL: %s %s = %d, expected %d" % (tag, pattern, got, want))

    for lang in LANG_PKGS:
        mbti = root / lang / "pkg.generated.mbti"
        if not mbti.is_file():
            fail("AD2-2 FAIL: %s is missing (run moon info first)" % mbti)
            continue
        pub = count_lines(mbti, r"^pub")
        stem = stem_count(mbti)
        lines.append("%s/pkg.generated.mbti  AD2-2 ^pub=%-3d want=3 %s | "
                     "AD2-8 stem_word raise count=%d want=1 %s"
                     % (lang, pub, "OK" if pub == 3 else "FAIL",
                        stem, "OK" if stem == 1 else "FAIL"))
        if pub != 3:
            fail("AD2-2 FAIL: %s ^pub = %d, expected 3" % (lang, pub))
        if stem != 1:
            fail("AD2-8 FAIL: %s stem_word(...raise @runtime.Lab) = %d, expected 1"
                 % (lang, stem))

    mbti_log.write_text("\n".join(lines) + "\n", encoding="utf-8")
    for line in lines:
        print(line)


# ---------------------------------------------------------------------------
# D-1 — semantic check, per package + fail-closed
# ---------------------------------------------------------------------------

def run_d1(root, target):
    proc = subprocess.run([sys.executable, "tools/d1check.py", str(target)],
                          cwd=str(root), capture_output=True, text=True)
    tail = (proc.stdout or proc.stderr).strip().splitlines()
    return proc.returncode, (tail[-1] if tail else "")


def check_d1(root, dialect_log):
    out = []
    ok = True
    for pkg in D1_PKGS:
        if not (root / pkg).is_dir():
            out.append("D-1 %-10s rc=2 MISSING PACKAGE" % pkg)
            ok = False
            continue
        rc, last = run_d1(root, pkg)
        out.append("D-1 %-10s rc=%d %s" % (pkg, rc, last))
        if rc != 0:
            ok = False

    # The root package (lang_registry.mbt) has no sub-directory of its own, and
    # passing the repository root to d1check would also scan .probe/ (the B7
    # defect: 508 files, 9 violations).  A temp copy of the root *.mbt keeps
    # the scan exactly as wide as the package.
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="t6-rootpkg-"))
    try:
        for f in sorted(root.glob("*.mbt")):
            shutil.copy2(f, tmp / f.name)
        files = sorted(p.name for p in tmp.glob("*.mbt"))
        rc, last = run_d1(root, tmp)
        out.append("D-1 %-10s rc=%d %s (temp copy of root: %s)"
                   % ("<root>", rc, last, ", ".join(files)))
        if rc != 0:
            ok = False
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    # fail-closed: a missing root and an empty directory are never a pass.
    missing = pathlib.Path(tempfile.gettempdir()) / "t6-definitely-absent-root"
    rc, last = run_d1(root, missing)
    out.append("D-1 fail-closed missing-root rc=%d %s (want 2)" % (rc, last))
    if rc != 2:
        ok = False
    empty = pathlib.Path(tempfile.mkdtemp(prefix="t6-empty-"))
    try:
        rc, last = run_d1(root, empty)
        out.append("D-1 fail-closed empty-dir rc=%d %s (want 3)" % (rc, last))
        if rc != 3:
            ok = False
    finally:
        shutil.rmtree(empty, ignore_errors=True)

    if not ok:
        fail("D-1 FAIL: see the per-package rows above")
    dialect_log.write_text("\n".join(out) + "\n", encoding="utf-8")
    for line in out:
        print(line)


# ---------------------------------------------------------------------------
# D-2..D-6 / D-12 / D-14 — retrieval greps
# ---------------------------------------------------------------------------

def package_files(root, rels):
    """Every .mbt inside the module-local packages, in stable order."""
    files = []
    for rel in sorted(rels):
        base = root / rel if rel else root
        for f in sorted(base.rglob("*.mbt")):
            parts = set(f.relative_to(root).parts[:-1])
            if parts & NON_DELIVERY_DIRS:
                continue
            files.append(f)
    return files


def grep_files(root, files, pattern, suffix=None):
    rx = re.compile(pattern)
    hits = []
    for f in files:
        if suffix and not f.name.endswith(suffix):
            continue
        for i, line in enumerate(f.read_text(encoding="utf-8",
                                              errors="replace").splitlines(), 1):
            if rx.search(line):
                hits.append("%s:%d: %s" % (f.relative_to(root).as_posix(), i,
                                           line.strip()))
    return hits


def check_d12(root):
    """D-12: the entry point must have an explicit non-zero exit path.

    Two shapes pass.  (a) `fn main` itself carries `raise`.  (b) `fn main` is
    a non-raising wrapper: it calls a function declared `raise`, and its own
    body ends in an explicit exit (`native_exit`, `abort`) — the shipped
    shape, where the top-level `catch` turns the raise into the driver's
    numeric exit code.

    Returns (ok, out_lines, message); `message` is the failure text.
    """
    exit_kw = ("native_exit", "abort")
    main_mbt = root / "cmd/golden/main.mbt"
    if not main_mbt.is_file():
        return False, [], "D-12 FAIL: cmd/golden/main.mbt is missing"
    lines = main_mbt.read_text(encoding="utf-8").splitlines()
    mains = [l for l in lines if re.search(r"\bfn main\b", l)]
    if not mains:
        return False, [], "D-12 FAIL: cmd/golden/main.mbt has no `fn main`"
    ok_a = all("raise" in l for l in mains)
    # The body of `fn main`: from its declaration to the brace that closes it.
    start = next(i for i, l in enumerate(lines) if re.search(r"\bfn main\b", l))
    body, depth = [], 0
    for l in lines[start:]:
        body.append(l)
        depth += l.count("{") - l.count("}")
        if len(body) > 1 and depth <= 0:
            break
    body_text = "\n".join(body)
    has_exit = any(k in body_text for k in exit_kw)
    callee = ""
    if has_exit:
        for l in lines:
            m = re.match(r"\s*fn\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(", l)
            if not m or m.group(1) == "main":
                continue
            name = m.group(1)
            if not re.search(r"\b%s\b" % re.escape(name), body_text):
                continue
            if re.search(r"\bfn\s+%s\b.*\braise\b" % re.escape(name), l):
                callee = name
                break
    ok = ok_a or bool(callee)
    out = ["D-12   %-28s hits=%d %s  %s" % ("explicit non-zero exit path",
                                            len(mains), "OK" if ok else "FAIL",
                                            mains[0].strip())]
    if callee:
        out.append("       fn main calls fn %s (declared raise); main ends in %s"
                   % (callee, "+".join(k for k in exit_kw if k in body_text)))
    msg = ("D-12 FAIL: cmd/golden/main.mbt has no explicit non-zero exit path "
           "(no raise and no native_exit/abort)")
    return ok, out, msg

def check_red_lines(root, rels, dialect_log):
    files = package_files(root, rels)
    out = ["D-2..D-6 / D-14 retrieval (D-12 is the exit-path check below), "
           "scoped to the %d module-local packages (%d .mbt files)"
           % (len(rels), len(files))]
    for tag, pattern, sub, _ in RED_LINES:
        suffix = sub.lstrip("*") or None
        hits = grep_files(root, files, pattern, suffix)
        out.append("%-6s %-28s hits=%-3d %s" % (tag, pattern, len(hits),
                                                "OK" if not hits else "FAIL"))
        for h in hits[:5]:
            out.append("       %s" % h)
        if hits:
            fail("%s FAIL: %d hit(s), expected 0" % (tag, len(hits)))

    # Attribution: the contract's literal `.`-scoped commands scan every .mbt
    # under the root except `_build/` and `.mooncakes/`, which also sweeps the
    # forensic archive (`.probe/`, `.planning/tmp/`).  Report those counts so
    # the narrowing is visible and attributed instead of silently dropped.
    delivery = set(files)
    literal = [p for p in root.rglob("*.mbt")
               if not ({"_build", ".mooncakes"} & set(p.relative_to(root).parts))
               and p not in delivery]
    for tag, pattern, sub, _ in RED_LINES[:5]:
        suffix = sub.lstrip("*") or None
        hits = grep_files(root, literal, pattern, suffix)
        heads = sorted({"/".join(h.split(":")[0].split("/")[:2]) for h in hits})
        out.append("%-6s literal '.'-scope (outside the 15 packages) hits=%d %s"
                   % (tag, len(hits),
                      "OK" if not hits else "ATTRIBUTED to " + ", ".join(heads)))

    # D-12: the entry point's explicit non-zero exit path (amended shape).
    ok, d12_out, d12_msg = check_d12(root)
    out.extend(d12_out)
    if not ok:
        fail(d12_msg)
    # D-14: the target key must be spelled exactly; a missing key silently
    # falls back to wasm.
    mod = (root / "moon.mod").read_text(encoding="utf-8", errors="replace")
    n = sum(1 for l in mod.splitlines() if l.strip() == 'preferred_target = "native"')
    out.append("D-14   %-28s hits=%d %s" % ('preferred_target = "native"', n,
                                            "OK" if n == 1 else "FAIL"))
    if n != 1:
        fail("D-14 FAIL: moon.mod has %d 'preferred_target = \"native\"' lines" % n)

    dialect_log.write_text("\n".join(out) + "\n", encoding="utf-8")
    for line in out:
        print(line)


# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(description="T6 compile-gate assertions")
    ap.add_argument("--json", default=None,
                    help="the moon check --json log (not re-read here; kept for plumbing)")
    ap.add_argument("--mbti-log", default=None)
    ap.add_argument("--dialect-log", default=None)
    args = ap.parse_args()

    root = pathlib.Path.cwd().resolve()
    if not (root / "moon.mod").is_file():
        print("check_gate: no moon.mod in %s (run from the module root)" % root,
              file=sys.stderr)
        return 2
    print("check_gate root=%s" % root)

    n, rels = check_packages(root)
    if not rels:
        rels = EXPECTED_RELS

    if args.mbti_log:
        check_mbti(root, pathlib.Path(args.mbti_log))
    else:
        check_mbti(root, pathlib.Path("T6-mbti.log"))

    if args.dialect_log:
        dialect_log = pathlib.Path(args.dialect_log)
    else:
        dialect_log = pathlib.Path("T6-dialect.log")
    # The D-1 rows and the retrieval rows share one log, in that order.
    d1_only = pathlib.Path(str(dialect_log) + ".d1")
    check_d1(root, d1_only)
    d1_text = d1_only.read_text(encoding="utf-8")
    d1_only.unlink()
    red_only = pathlib.Path(str(dialect_log) + ".red")
    check_red_lines(root, rels, red_only)
    red_text = red_only.read_text(encoding="utf-8")
    red_only.unlink()
    dialect_log.write_text(d1_text + red_text, encoding="utf-8")

    if FAILS:
        print("")
        for f in FAILS:
            print("GATE FAIL: %s" % f, file=sys.stderr)
        return 1
    print("GATE PASS packages=%d" % (n if n else 0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
